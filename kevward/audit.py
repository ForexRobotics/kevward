# Login shells a would-be attacker account would use; a nologin/false shell
# means the account can't log in, so an empty password there is not a finding.
_NOLOGIN_SHELLS = {
    "", "/usr/sbin/nologin", "/sbin/nologin", "/bin/false", "/usr/bin/false",
    "/dev/null",
}

# Shell/interpreter basenames whose setuid copy is a classic root backdoor.
_SUID_INTERP = {
    "bash", "sh", "dash", "zsh", "ksh", "ash", "busybox",
    "python", "perl", "ruby", "lua", "php", "node",
    "env", "awk", "gawk", "find", "vim", "nmap", "tclsh", "expect",
}

_SUDO_NOPASSWD_ALL = re.compile(r"\bNOPASSWD:\s*ALL\b", re.I)
_RC_CRED = r"(sudo|ssh|su|passwd|doas)"


def classify_passwd_line(line: str) -> str | None:
    """Flag a ``/etc/passwd`` line that is a rogue account. Conservative: only
    a UID-0 account other than ``root`` (a hidden second superuser)."""
    parts = line.rstrip("\n").split(":")
    if len(parts) < 7:
        return None
    name, uid = parts[0], parts[2]
    try:
        uidn = int(uid)
    except ValueError:
        return None
    if uidn == 0 and name != "root":
        return "UID 0 account other than root"
    return None


def classify_shadow_line(line: str) -> str | None:
    """Return the account name if its ``/etc/shadow`` password field is empty
    (login with no password), else None. ``*`` / ``!`` are locked, not empty."""
    parts = line.rstrip("\n").split(":")
    if len(parts) < 2:
        return None
    name, pw = parts[0], parts[1]
    return name if pw == "" else None


def locked_accounts(shadow_text: str) -> set[str]:
    """Accounts whose ``/etc/shadow`` password is locked or unset (``!...``,
    ``*``, ``!!``). Pure; never returns or keeps the hash itself."""
    out: set[str] = set()
    for ln in shadow_text.splitlines():
        parts = ln.split(":")
        if len(parts) >= 2 and parts[1][:1] in ("!", "*"):
            out.add(parts[0])
    return out


_ACCEPTED_PW = re.compile(
    r"sshd\[\d+\]: Accepted (password|keyboard-interactive/pam) for "
    r"(?:invalid user )?(\S+) from (\S+) port \d+"
)


def password_off_since(files: list[tuple[str, float, str]]) -> tuple[float, str] | None:
    """When ``PasswordAuthentication no`` was configured, as (mtime, path). Pure.

    ``files`` are (path, mtime, text) for sshd_config and sshd_config.d/*.conf.
    The earliest mtime among files with an active ``PasswordAuthentication no``
    line is used: a later edit of that file only makes the cutoff later, never
    earlier, so a login after the setting took effect is never excused by an
    old timestamp. File mtime is a proxy for "when it was set" (#87 follow-up).
    """
    best: tuple[float, str] | None = None
    for path, mtime, text in files:
        for ln in text.splitlines():
            parts = ln.split("#", 1)[0].split()
            if len(parts) >= 2 and parts[0].lower() == "passwordauthentication" \
                    and parts[1].lower() == "no":
                if best is None or mtime < best[0]:
                    best = (mtime, path)
                break
    return best


def accepted_password_logins(
    lines, locked: set[str], password_auth_disabled: bool | None,
    off_since: float | None = None, now=None,
) -> list[tuple[str, str, str, int, str, bool]]:
    """Password logins that should be impossible on this host (#87). Pure.

    Flags ``Accepted password`` when sshd has ``PasswordAuthentication no``
    or the account's password is locked, and ``Accepted keyboard-interactive/pam``
    only for a locked account (PAM may legitimately run OTP there). Such a line
    means authentication succeeded by a path that should not exist, the shape
    of auth-bypass bugs like SSHole (CVE-2026-123158).

    ``off_since`` (epoch seconds, see ``password_off_since``): a password
    login logged *before* PasswordAuthentication was turned off is not a
    bypass, e.g. a host's initial setup (www2, 2026-10-25). Such lines are
    returned with ``before=True``; locked-account logins are never excused,
    and a line whose time cannot be read counts as after.

    Returns ``(user, source ip, method, count, last line, before)`` per
    user/source/method/before.
    """
    from datetime import datetime

    from .integrations.logwatch import parse_log_time
    now = now or datetime.now().astimezone()
    seen: dict[tuple[str, str, str, bool], list] = {}
    for line in lines:
        m = _ACCEPTED_PW.search(line)
        if not m:
            continue
        method, user, ip = m.group(1), m.group(2), m.group(3)
        bad = user in locked or (method == "password" and password_auth_disabled is True)
        if not bad:
            continue
        before = False
        if off_since is not None and user not in locked:
            ts = parse_log_time(line, now)
            before = ts is not None and ts.timestamp() < off_since
        key = (user, ip, method, before)
        if key in seen:
            seen[key][0] += 1
            seen[key][1] = line.strip()
        else:
            seen[key] = [1, line.strip()]
    return [(u, ip, meth, n, last, before)
            for (u, ip, meth, before), (n, last) in seen.items()]


def _sshd_config_files() -> list[tuple[str, float, str]]:
    out: list[tuple[str, float, str]] = []
    for path in ["/etc/ssh/sshd_config", *sorted(glob.glob("/etc/ssh/sshd_config.d/*.conf"))]:
        try:
            st = os.stat(path)
            with open(path, errors="replace") as fh:
                out.append((path, st.st_mtime, fh.read()))
        except OSError:
            continue
    return out


def _check_accepted_password(log_glob: str = "/var/log/auth.log*") -> list[Finding]:
    """HIGH for each password login the host's own settings rule out (#87)."""
    from .integrations.conditions import _read_sshd_t
    from .integrations.logwatch import _iter_lines
    try:
        with open("/etc/shadow", errors="replace") as fh:
            locked = locked_accounts(fh.read())
    except OSError:
        locked = set()  # not root: rely on sshd -T alone
    pa = _read_sshd_t().get("passwordauthentication")
    disabled = None if pa is None else pa == "no"
    if not locked and disabled is not True:
        return []  # nothing could rule a password login out
    since = password_off_since(_sshd_config_files()) if disabled else None
    out: list[Finding] = []
    for user, ip, method, n, last, before in accepted_password_logins(
            _iter_lines(log_glob), locked, disabled,
            off_since=since[0] if since else None):
        if before and since:
            from datetime import datetime
            when = datetime.fromtimestamp(since[0]).astimezone()
            out.append(_f(Severity.INFO,
                          f"ssh {method} login for {user} from {ip} before password "
                          f"logins were turned off ({n}x)",
                          detail=f"last: {last[:200]} — PasswordAuthentication no is set in "
                                 f"{since[1]} (file changed {when:%Y-%m-%d %H:%M %Z}); "
                                 "these logins predate it, e.g. initial setup. "
                                 "Confirm the source address is yours."))
            continue
        why = ("its password is locked" if user in locked
               else "sshd has PasswordAuthentication no")
        out.append(_f(Severity.HIGH,
                      f"ssh {method} login accepted for {user} from {ip}, but {why} "
                      f"({n}x)",
                      detail=f"last: {last[:200]} — possible authentication bypass; "
                             "investigate this session and the sshd build"))
    return out


def classify_sudoers_line(line: str) -> str | None:
    """Flag a passwordless-to-everything sudoers grant. Kept narrow (only
    ``NOPASSWD: ALL``) so ordinary ``user ALL=(ALL) ALL`` does not fire."""
    s = line.strip()
    if not s or s.startswith("#") or s.startswith("Defaults"):
        return None
    if _SUDO_NOPASSWD_ALL.search(s):
        return "passwordless sudo to ALL (NOPASSWD: ALL)"
    return None


def classify_suid(path: str) -> str | None:
    """Why a setuid/setgid file looks suspicious, or None. The caller has
    already confirmed the suid/sgid bit; this decides *where/what* is wrong.

    Legitimate system suid binaries (``sudo``, ``passwd``, ``mount``, …) are not
    shells and live in standard paths, so they do not match."""
    if _SUSPECT_EXE_DIR.match(path) or "/." in path:
        return "setuid/setgid file in a temp or hidden path"
    base = os.path.basename(path)
    stem = re.sub(r"[0-9.]+$", "", base)  # python3.11 -> python
    if base in _SUID_INTERP or stem in _SUID_INTERP:
        return "setuid/setgid shell or interpreter"
    return None


def classify_rc_line(line: str) -> str | None:
    """Flag a shell-rc credential hijack (distinct from a reverse shell): a
    function or redirecting alias wrapping ``sudo``/``ssh``/``su``/``passwd``,
    or ``PROMPT_COMMAND``/``BASH_ENV`` wired to run something. A plain
    convenience alias is deliberately not flagged."""
    s = line.strip()
    if not s or s.startswith("#"):
        return None
    m = re.match(rf"(?:function\s+)?{_RC_CRED}\s*\(\s*\)", s)
    if m:
        return f"shell function overrides '{m.group(1)}'"
    am = re.match(rf"alias\s+{_RC_CRED}\s*=\s*(.+)$", s)
    if am:
        val = am.group(2)
        if re.search(r">>?\s*\S|;|\|\||&&|\$\(|`|/dev/|/tmp/", val):
            return f"alias '{am.group(1)}' redirects or chains a command"
        return None
    if re.match(r"(?:export\s+)?PROMPT_COMMAND\s*=", s) and (
        is_suspicious_cmdline(s) or _TEMP_PATH.search(s)
    ):
        return "PROMPT_COMMAND runs a suspicious command"
    if re.match(r"(?:export\s+)?BASH_ENV\s*=", s):
        return "BASH_ENV set (runs a script for non-interactive bash)"
    return None


def _check_accounts() -> list[Finding]:
    out: list[Finding] = []
    login_accounts: dict[str, str] = {}
    try:
        with open("/etc/passwd", errors="replace") as fh:
            for ln in fh:
                reason = classify_passwd_line(ln)
                if reason:
                    name = ln.split(":", 1)[0]
                    out.append(_f(Severity.HIGH, f"{reason}: {name}",
                                  detail=ln.strip()[:200]))
                parts = ln.rstrip("\n").split(":")
                if len(parts) >= 7 and parts[6] not in _NOLOGIN_SHELLS:
                    login_accounts[parts[0]] = parts[6]
    except OSError:
        pass
    try:
        with open("/etc/shadow", errors="replace") as fh:
            for ln in fh:
                name = classify_shadow_line(ln)
                if name and name in login_accounts:
                    out.append(_f(Severity.HIGH,
                                  f"login account with an empty password: {name}",
                                  detail="set a password or lock the account"))
    except OSError:
        pass  # not root / no shadow readable
    sfiles = ["/etc/sudoers"]
    try:
        sfiles += [os.path.join("/etc/sudoers.d", n)
                   for n in os.listdir("/etc/sudoers.d")]
    except OSError:
        pass
    for sf in sfiles:
        try:
            st = os.stat(sf)
        except OSError:
            continue
        if st.st_mode & 0o022:
            out.append(_f(Severity.HIGH,
                          f"sudoers file is group/world-writable: {sf}",
                          detail=f"mode {oct(st.st_mode & 0o777)}"))
        try:
            with open(sf, errors="replace") as fh:
                for ln in fh:
                    reason = classify_sudoers_line(ln)
                    if reason:
                        out.append(_f(Severity.MEDIUM, f"{reason} in {sf}",
                                      detail=ln.strip()[:200]))
        except OSError:
            continue
    return out


_SUID_SCAN_DIRS = [
    "/usr/bin", "/usr/sbin", "/bin", "/sbin", "/usr/local/bin",
    "/usr/local/sbin", "/opt", "/tmp", "/var/tmp", "/dev/shm",
]


def _check_suid(max_report: int = 40, max_files: int = 60000) -> list[Finding]:
    out: list[Finding] = []
    seen = 0
    for d in _SUID_SCAN_DIRS + _home_dirs():
        for root, _dirs, files in os.walk(d, onerror=lambda e: None):
            for fn in files:
                seen += 1
                if seen > max_files:
                    return out
                p = os.path.join(root, fn)
                if os.path.islink(p):
                    continue
                try:
                    st = os.lstat(p)
                except OSError:
                    continue
                if not st.st_mode & 0o6000:  # no setuid/setgid bit
                    continue
                reason = classify_suid(p)
                if reason:
                    out.append(_f(Severity.HIGH, f"{reason}: {p}",
                                  detail=f"mode {oct(st.st_mode & 0o7777)} "
                                         f"uid {st.st_uid}"))
                    if len(out) >= max_report:
                        return out
    return out


