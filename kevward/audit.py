def _print_findings(findings: list[Finding]) -> None:
    if not findings:
        print("  ok — no compromise indicators found")
        return
    for f in findings:
        sev = f.severity.value if hasattr(f.severity, "value") else f.severity
        print(f"  - {sev.upper():7} {f.title}")
        if f.detail:
            print(f"            {f.detail}")


def run_cli(use_json: bool, allow_forced: list[str] | None = None,
            allowed_outbound: list[str] | None = None) -> int:
    notes: dict = {}
    findings = audit(allow_forced, allowed_outbound, notes)
    if use_json:
        import json

        from .jsonout import findings_doc
        print(json.dumps(findings_doc(
            findings, allowed_outbound_hits=notes.get("allowed_outbound_hits") or {},
            allowed_forced_hits=notes.get("allowed_forced_hits") or {}),
            indent=2, ensure_ascii=False))
    else:
        _print_findings(findings)
        line = allowed_summary(notes.get("allowed_outbound_hits"))
        if line:
            print(f"  ({line} — [audit] allowed_outbound)")
        if not is_root():
            print("note: run with sudo for full visibility into other users' "
                  "processes, sockets and files.")
    # Read-only: exit 0 regardless. The findings themselves are the signal.
    return 0
