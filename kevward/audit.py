def _check_user_units() -> list[Finding]:
    """User-level systemd service units — a persistence spot the system-unit
    scan misses. A malicious timer's payload is its paired ``.service``, caught
    here (user) or by ``_check_units`` (system)."""
    out: list[Finding] = []
    bases = ["/etc/systemd/user", "/run/systemd/user"]
    for home in ["/root", *_home_dirs()]:
        bases.append(os.path.join(home, ".config/systemd/user"))
    for base in bases:
        try:
            names = [n for n in os.listdir(base) if n.endswith(".service")]
        except OSError:
            continue
        for n in names:
            try:
                with open(os.path.join(base, n), errors="replace") as fh:
                    for ln in fh:
                        s = ln.strip()
                        if s.startswith("ExecStart"):
                            reason = is_suspicious_exec(s)
                            if reason:
                                out.append(_f(
                                    Severity.HIGH,
                                    f"suspicious user unit {n}: {reason}",
                                    detail=s[:200]))
            except OSError:
                continue
    return out


def audit(allow_forced: list[str] | None = None,
          allowed_outbound: list[str] | None = None,
          notes: dict | None = None) -> list[Finding]:
    """Run every check. ``notes``, when given, receives
    ``allowed_outbound_hits`` (rule -> connections it silenced, #155)."""
    rules, errors = parse_outbound_allow(allowed_outbound)
    # Every configured rule is reported, at 0 when nothing matched (#175), so
    # "no connection at scan time" differs from "rule not configured".
    hits: dict[str, int] = {r.text: 0 for r in rules}
    bad = [_f(Severity.LOW, f"[audit] allowed_outbound: ignored entry {e}")
           for e in errors]
    forced_hits: dict[str, int] = {p: 0 for p in (allow_forced or [])}
    findings = (bad + check_reverse_ssh() + check_connections(allow=rules, hits=hits)
                + check_persistence(allow_forced, forced_hits)
                + _check_proc_origin() + _check_pkg_integrity()
                + _check_accounts() + _check_accepted_password() + _check_suid())
    findings.sort(key=lambda f: f.severity.rank, reverse=True)
    if notes is not None:
        notes["allowed_outbound_hits"] = hits
        notes["allowed_forced_hits"] = forced_hits
    return findings


def forced_summary(hits: dict[str, int] | None) -> str:
    """``allowed forced commands: 1 key (pattern)``, or with patterns that
    matched nothing ``…: 0 (patterns: …; no key matched)`` (#224); "" when no
    pattern is configured."""
    if not hits:
        return ""
    total = sum(hits.values())
    if total == 0:
        return (f"allowed forced commands: 0 (patterns: {', '.join(sorted(hits))}; "
                "no authorized_keys entry matched)")
    matched = ", ".join(sorted(k for k, v in hits.items() if v))
    idle = sorted(k for k, v in hits.items() if not v)
    tail = f"; no match: {', '.join(idle)}" if idle else ""
    return f"allowed forced commands: {total} ({matched}{tail})"


def allowed_summary(hits: dict[str, int] | None) -> str:
    """``allowed outbound: 2 (tor:9001)``; with rules but no match (#175)
    ``allowed outbound: 0 (rules: tor:9001; no matching connection at scan
    time)``; "" when no rule is configured."""
    if not hits:
        return ""
    total = sum(hits.values())
    if total == 0:
        return (f"allowed outbound: 0 (rules: {', '.join(sorted(hits))}; "
                "no matching connection at scan time)")
    matched = {k: v for k, v in hits.items() if v}
    rules = ", ".join(f"{k} ×{v}" if v > 1 and len(matched) > 1 else k
                      for k, v in sorted(matched.items()))
    idle = sorted(k for k, v in hits.items() if not v)
    tail = f"; no match: {', '.join(idle)}" if idle else ""
    return f"allowed outbound: {total} ({rules}{tail})"


